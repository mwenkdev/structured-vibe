// Command gen produces the embedded managed-file manifest.
//
// The expected managed path/hash set is embedded in the svibe binary at build
// time. It is deliberately not installed as a separate authoritative manifest
// alongside the payload, because a manifest that ships next to the files it
// describes can be edited to match them (architecture 16.1).
//
// The public source repository remains the place to inspect how this data is
// built. Do not hand-edit the generated output; run "make generate".
package main

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"go/format"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strings"
)

// managedRoots are repository directories whose contents become managed
// runtime payload, mapped to their path inside the installed config root.
var managedRoots = []struct{ repo, install string }{
	{repo: "core", install: "core"},
	{repo: "config", install: "config"},
	// Built integration output. It is produced by "make plugin" and is not
	// committed, so "make generate" depends on the plugin being built first.
	{repo: "integrations/opencode/dist", install: "integrations/opencode"},
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run() error {
	// go:generate runs with the working directory set to the package
	// directory. Locate the repository root by its go.mod rather than
	// counting parent directories, so the generator keeps working if it moves.
	repoRoot, err := findRepoRoot()
	if err != nil {
		return err
	}

	hashes := map[string]string{}
	for _, root := range managedRoots {
		dir := filepath.Join(repoRoot, root.repo)
		if _, err := os.Stat(dir); os.IsNotExist(err) {
			continue
		}
		if err := hashTree(dir, root.install, hashes); err != nil {
			return fmt.Errorf("hashing %s: %w", root.repo, err)
		}
	}

	keys := make([]string, 0, len(hashes))
	for k := range hashes {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var b strings.Builder
	b.WriteString("// Code generated by internal/managed/gen. DO NOT EDIT.\n\n")
	b.WriteString("package managed\n\n")
	b.WriteString("// expected is the managed runtime payload shipped with this release,\n")
	b.WriteString("// keyed by path relative to the svibe config root.\n")
	b.WriteString("var expected = map[string]string{\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "\t%q: %q,\n", k, hashes[k])
	}
	b.WriteString("}\n")

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return fmt.Errorf("formatting generated source: %w", err)
	}

	out := filepath.Join(repoRoot, "internal", "managed", "manifest_gen.go")
	return os.WriteFile(out, src, 0o644)
}

// findRepoRoot walks up from the working directory looking for go.mod.
func findRepoRoot() (string, error) {
	cur, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(cur, "go.mod")); err == nil {
			return cur, nil
		}
		parent := filepath.Dir(cur)
		if parent == cur {
			return "", fmt.Errorf("cannot locate repository root: no go.mod above %s", cur)
		}
		cur = parent
	}
}

// hashTree records the SHA-256 of every regular file beneath dir, keyed by
// its slash-separated install-relative path.
func hashTree(dir, installPrefix string, out map[string]string) error {
	return filepath.WalkDir(dir, func(p string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() || !entry.Type().IsRegular() {
			return nil
		}
		rel, err := filepath.Rel(dir, p)
		if err != nil {
			return err
		}
		raw, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		sum := sha256.Sum256(raw)
		key := path.Join(installPrefix, filepath.ToSlash(rel))
		out[key] = hex.EncodeToString(sum[:])
		return nil
	})
}
